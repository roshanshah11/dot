#!/opt/homebrew/bin/python3.13
"""Write Resources/board/viz/index.js: window.VIZ_INDEX = [{id, title, subject, shows}, ...] for every widget that
passes viz-check (docs/catalog-status.json), so the panel can resolve <viz topic="..."> and Dot's prompt can list them.
Run after building widgets: scripts/viz-index.py [--all]  (--all includes widgets not yet checked)."""
import json, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
ROOT = Path(__file__).resolve().parent.parent
spec = __import__("importlib.util").util.spec_from_file_location("viz_find", ROOT / "scripts" / "viz-find.py")
vf = __import__("importlib.util").util.module_from_spec(spec); spec.loader.exec_module(vf)
items = vf.index()
if "--all" not in sys.argv:
    ledger = json.loads((ROOT / "docs" / "catalog-status.json").read_text()).get("widgets", {})
    items = [it for it in items if ledger.get(it["id"], {}).get("status") == "pass"]
out = ROOT / "Resources" / "board" / "viz" / "index.js"
out.write_text("// Generated by scripts/viz-index.py: the explainers that pass viz-check.\nwindow.VIZ_INDEX = " + json.dumps(items, indent=0, ensure_ascii=False) + ";\n")
print(f"{len(items)} widgets in {out.relative_to(ROOT)}")
